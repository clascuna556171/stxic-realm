// Isolated anonymous previews: never signs in or writes to the hosted backend.
import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const origin = process.env.REALM_UI_ORIGIN ?? 'http://127.0.0.1:5175'
const output = resolve(import.meta.dirname, '../../../.impeccable/review/world-overhaul')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: process.env.REALM_BROWSER_CHANNEL ?? 'chrome', headless: true })
const errors = [], checks = []
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
const page = await context.newPage()
page.on('pageerror', error => errors.push(error.message))
const noOverflow = async () => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'horizontal overflow')
try {
 await page.goto(origin + '/?hall-preview')
 await page.getByRole('heading', { name: 'Server Halls' }).waitFor()
 await page.locator('.hall-pixel-canvas').waitFor()
 await page.evaluate(() => document.fonts.ready)
 assert.equal(await page.locator('.hall-pixel-canvas').evaluate(canvas => canvas.width), 768)
 await page.getByRole('button', { name: 'Select Moonlit Archive', exact: true }).click()
 assert.equal(await page.locator('.hall-selected h3').innerText(), 'Moonlit Archive')
 await page.getByLabel('Find a server').fill('workshop')
 assert.equal(await page.locator('.hall-server-list>button').count(), 1)
 await page.locator('.hall-server-list>button').focus()
 await page.keyboard.press('Enter')
 assert.equal(await page.locator('.hall-selected h3').innerText(), 'The Workshop')
 await page.getByLabel('Find a server').fill('')
 await page.getByRole('button', { name: 'Ambient effects On' }).click()
 assert.equal(await page.locator('.hall-embers').count(), 0)
 await page.getByRole('button', { name: 'Ambient effects Off' }).click()
 await noOverflow()
 await page.screenshot({ path: resolve(output, 'hall-desktop.png'), fullPage: true })
 checks.push('Guest preview: entrances, directory search, keyboard selection, ambient effects, asset loading')
 await page.setViewportSize({ width: 390, height: 844 })
 await noOverflow()
 await page.screenshot({ path: resolve(output, 'hall-phone.png'), fullPage: true })
 await page.setViewportSize({ width: 320, height: 740 })
 await noOverflow()
 await page.setViewportSize({ width: 390, height: 844 })
 await page.emulateMedia({ reducedMotion: 'reduce' })
 assert.equal(await page.locator('.hall-embers').evaluate(e => getComputedStyle(e).display), 'none')
 await page.emulateMedia({ reducedMotion: 'no-preference' })
 checks.push('Phone layout and reduced motion')
 await page.setViewportSize({ width: 1440, height: 1000 })
 await page.goto(origin + '/?appearance')
 await page.getByRole('button', { name: 'medieval', exact: true }).click()
 await page.getByRole('button', { name: 'Save appearance', exact: true }).click()
 await page.reload()
 assert.equal(await page.getByRole('button', { name: 'medieval', exact: true }).getAttribute('aria-pressed'), 'true')
 await page.screenshot({ path: resolve(output, 'character-desktop.png'), fullPage: true })
 await page.setViewportSize({ width: 390, height: 844 })
 await noOverflow()
 await page.screenshot({ path: resolve(output, 'character-phone.png'), fullPage: true })
 checks.push('Character customization persists across reload; desktop/phone alcove stage')
 await page.goto(origin + '/?room-preview')
 await page.locator('.room-canvas canvas').waitFor()
 await page.locator('.walk-menu summary').click()
 await page.getByRole('button', { name: 'Move left', exact: true }).click()
 await page.locator('.room-main').getByText('Column 8 · Row 10', { exact: true }).waitFor()
 await page.getByRole('button',{name:'Objects & details',exact:true}).click()
 await page.locator('.room-object-list button').filter({ hasText: 'Lantern' }).click()
 assert.equal(await page.locator('.room-object-detail h3').innerText(), 'Lantern')
 await noOverflow()
 await page.screenshot({ path: resolve(output, 'room-phone.png'), fullPage: true })
 await page.setViewportSize({ width: 1440, height: 1000 })
 await page.screenshot({ path: resolve(output, 'room-desktop.png'), fullPage: true })
 await page.goto(origin + '/?room-studio')
 await page.locator('.room-canvas canvas').waitFor()
 await page.getByRole('button', { name: 'Remove', exact: true }).click()
 await page.getByRole('button', { name: 'Undo', exact: true }).click()
 await page.getByRole('button', { name: 'Redo', exact: true }).waitFor()
 await page.screenshot({ path: resolve(output, 'studio-desktop.png'), fullPage: true })
 checks.push('Room rendering, movement, inspection; Studio removal and undo')
 assert.deepEqual(errors, [])
 await writeFile(resolve(output, 'verification.json'), JSON.stringify({ checks, pageErrors: errors }, null, 2))
 console.log('PASS: ' + checks.join('; '))
} catch (error) {
 await page.screenshot({ path: resolve(output, 'failure.png'), fullPage: true })
 console.error((await page.locator('body').innerText()).slice(0, 2500))
 throw error
} finally { await browser.close() }
