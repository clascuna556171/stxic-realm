"""Compile the selected Sprite Fusion furnishing to compact pixel rectangles.

Build-time art pipeline only (Pillow); the app needs no image-processing dependency.
Source artwork stays untouched in docs/images/spritefusion.
"""
from pathlib import Path
from PIL import Image
import json

root = Path(__file__).resolve().parents[3]
image = Image.open(root / 'docs/images/spritefusion/shelf-7.png').convert('RGBA')
image = image.crop(image.getbbox()).resize((64, 80), Image.Resampling.NEAREST)
alpha = image.getchannel('A')
image = image.convert('RGB').quantize(colors=48, dither=Image.Dither.NONE).convert('RGBA')
image.putalpha(alpha)
runs, active = [], {}
for y in range(image.height):
    row, x = {}, 0
    while x < image.width:
        color = image.getpixel((x, y))
        if color[3] < 128:
            x += 1
            continue
        start = x
        while x < image.width and image.getpixel((x, y)) == color:
            x += 1
        key = (start, x - start, '#%02x%02x%02x' % color[:3])
        if key in active:
            index = active[key]
            runs[index][3] += 1
        else:
            index = len(runs)
            runs.append([start, y - 16, x - start, 1, key[2]])
        row[key] = index
    active = row
target = root / 'apps/web/src/world/spritefusion-shelf.ts'
target.write_text('// Generated by scripts/compile-spritefusion.py; source: Sprite Fusion asset b88ae9c9-4488-4536-809e-bf0b8e10977f.\n'
                  'export const shelfRuns: [number, number, number, number, string][] = '
                  + json.dumps(runs, separators=(',', ':')) + '\n', encoding='utf-8')
print(f'Compiled {len(runs)} rectangles into {target.name}')
